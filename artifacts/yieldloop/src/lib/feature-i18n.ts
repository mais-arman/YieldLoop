export type { FKey };
const dict = { en, ar };
export type Ft = (k: FKey, vars?: Record<string, string | number>) => string;
export function useFt(): Ft {
  const { lang } = useI18n();
  return useCallback((k, vars) => {
    let s = dict[lang][k] ?? en[k];
    if (vars) for (const [vk, vv] of Object.entries(vars)) s = s.replace(`{${vk}}`, String(vv));
    return s;
  }, [lang]);
}
export function hasFKey(k: string): k is FKey { return k in en; }

